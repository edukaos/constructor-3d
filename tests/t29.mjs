// Grabado: el texto se ubica tocando la cara, la profundidad se cambia en el panel y Escape cancela
import {open,check,summary} from './lib.mjs';
const {browser,page,errs}=await open();
await page.click('#pnew'); await page.waitForTimeout(200);
await page.keyboard.press('1'); await page.waitForTimeout(100);
await page.click('#textbtn'); await page.waitForTimeout(200);
await page.fill('#tstr','HI');
await page.evaluate(()=>{select([objs[0]]);});
const n0=await page.evaluate(()=>objs.length);
await page.click('#tgrab'); await page.waitForTimeout(800);
check('Al empezar aparece el texto de vista previa',await page.evaluate(()=>objs.length)===n0+1,'');
check('El botón pasa a Confirmar grabado',(await page.textContent('#tgrab')).includes('Confirmar'),await page.textContent('#tgrab'));
const pt=await page.evaluate(()=>{const r=canvas.getBoundingClientRect(); const b=bbox(objs[0]); const v=new THREE.Vector3(b.min.x+(b.max.x-b.min.x)*0.25,b.max.y,(b.min.z+b.max.z)/2).project(cam); return {x:r.left+(v.x+1)/2*r.width,y:r.top+(1-v.y)/2*r.height};});
await page.mouse.move(pt.x,pt.y); await page.waitForTimeout(60); await page.mouse.down(); await page.mouse.up(); await page.waitForTimeout(100);
const cx=await page.evaluate(()=>objs[objs.length-1].position.x);
const cube=await page.evaluate(()=>{const b=bbox(objs[0]); return (b.min.x+b.max.x)/2;});
check('El texto quedó corrido hacia el lado tocado',cx < cube-3,'texto x='+cx.toFixed(1)+' cubo x='+cube.toFixed(1));
const d0=await page.evaluate(()=>{const g=objs[objs.length-1].geometry; g.computeBoundingBox(); return g.boundingBox.max.y-g.boundingBox.min.y;});
await page.fill('#tdepth','6'); await page.dispatchEvent('#tdepth','input'); await page.waitForTimeout(1500);
const d1=await page.evaluate(()=>{const g=objs[objs.length-1].geometry; g.computeBoundingBox(); return g.boundingBox.max.y-g.boundingBox.min.y;});
check('Cambiar la profundidad cambia el espesor del texto',Math.abs(d1-6)<0.05&&Math.abs(d0-d1)>0.5,`antes ${d0.toFixed(2)} ahora ${d1.toFixed(2)}`);
await page.keyboard.press('Escape'); await page.waitForTimeout(150);
check('Escape cancela y saca el texto de vista previa',await page.evaluate(()=>objs.length)===n0,'');
check('El botón vuelve a Grabar en la pieza',(await page.textContent('#tgrab')).includes('Grabar'),'');
check('Sin errores',errs.length===0,errs.join('|'));
summary(); await browser.close();
